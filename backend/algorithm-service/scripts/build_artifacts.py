"""Rebuild scoring artifacts from the delivered joblib model.

The model file is supplied by the project owner (generated by 1108.py) and is
never retrained here. This script reproduces that script's grid and holdout
split, measures the model against the deterministic rule on the holdout set,
then writes the dataset, metrics, metadata and checksum manifest.

Eligibility is derived from measured metrics only. Values are never tuned or
fabricated to pass a threshold.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any

import joblib
import numpy as np
from sklearn.model_selection import train_test_split

from app.dataset import (
    FEATURE_ORDER,
    TARGET_COLUMN,
    build_grid_frame,
    dataset_csv_bytes,
)
from app.rules import BOOST_CAP, MAX_SCORE, MIN_SCORE, RULE_VERSION


MODEL_FILENAME = "score-model.joblib"
DATASET_FILENAME = "score-samples.csv"
THRESHOLDS: dict[str, float] = {"rmseMax": 1.0, "maeMax": 0.8, "r2Min": 0.99}
SPLIT_SEED = 42
MODEL_KEY = "smoothstep-score"
DEFAULT_DIR = Path(__file__).resolve().parents[1] / "artifacts"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, value: dict[str, Any]) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def _metrics(actual: np.ndarray, predicted: np.ndarray) -> dict[str, float]:
    errors = predicted - actual
    rmse = math.sqrt(float(np.mean(errors * errors)))
    mae = float(np.mean(np.abs(errors)))
    denominator = float(np.sum((actual - float(np.mean(actual))) ** 2))
    r2 = 1.0 - float(np.sum(errors * errors)) / denominator
    return {"rmse": rmse, "mae": mae, "r2": r2}


def build(root: Path) -> dict[str, Any]:
    root.mkdir(parents=True, exist_ok=True)
    model_path = root / MODEL_FILENAME
    if not model_path.is_file():
        raise FileNotFoundError(f"missing model artifact: {model_path}")

    frame = build_grid_frame()
    X = frame[FEATURE_ORDER]
    y = frame[TARGET_COLUMN]
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=SPLIT_SEED
    )

    model = joblib.load(model_path)
    names_attr = getattr(model, "feature_names_in_", None)
    names = [str(name) for name in names_attr] if names_attr is not None else []
    if names and names != FEATURE_ORDER:
        raise ValueError(f"model feature names mismatch: {names}")

    predicted = np.asarray(model.predict(X_test), dtype=float)
    actual = y_test.to_numpy(dtype=float)
    measured = _metrics(actual, predicted)
    eligible = (
        measured["rmse"] <= THRESHOLDS["rmseMax"]
        and measured["mae"] <= THRESHOLDS["maeMax"]
        and measured["r2"] >= THRESHOLDS["r2Min"]
    )

    dataset_path = root / DATASET_FILENAME
    dataset_path.write_bytes(dataset_csv_bytes(frame))
    dataset_hash = _sha256(dataset_path)
    model_hash = _sha256(model_path)

    metrics = {
        "holdout": measured,
        "thresholds": THRESHOLDS,
        "eligible": eligible,
        "split": {
            "method": "sklearn.model_selection.train_test_split",
            "testSize": 0.2,
            "randomState": SPLIT_SEED,
            "trainingRows": int(len(X_train)),
            "testRows": int(len(X_test)),
            "datasetRows": int(len(frame)),
        },
        "note": "Model is fitted to the deterministic rule grid; metrics measure agreement with the rule, not real student data.",
    }
    _write_json(root / "metrics.json", metrics)

    version = f"smoothstep-xgb-{model_hash[:12]}"
    metadata: dict[str, Any] = {
        "artifactUri": f"algorithm-service://artifacts/{MODEL_FILENAME}",
        "boostCap": BOOST_CAP,
        "datasetRows": int(len(frame)),
        "datasetSha256": dataset_hash,
        "eligibilityThresholds": THRESHOLDS,
        "featureOrder": FEATURE_ORDER,
        "featureSchema": [
            {
                "jsonField": "standardGroupSize",
                "name": "标准人数",
                "type": "int32",
                "minimum": 1,
                "maximum": 4,
            },
            {
                "jsonField": "contribution",
                "name": "个人贡献度",
                "type": "float64",
                "minimum": 0.0,
                "maximum": 1.0,
            },
            {
                "jsonField": "groupScore",
                "name": "作业总分",
                "type": "float64",
                "minimum": 0.0,
                "maximum": 100.0,
            },
        ],
        "modelFormat": "joblib-sklearn",
        "modelKey": MODEL_KEY,
        "modelSha256": model_hash,
        "modelType": "xgboost-regression",
        "parameters": {
            "n_estimators": int(getattr(model, "n_estimators", 0)),
            "max_depth": int(getattr(model, "max_depth", 0)),
            "learning_rate": float(getattr(model, "learning_rate", 0.0)),
            "random_state": SPLIT_SEED,
        },
        "ruleVersion": RULE_VERSION,
        "schemaVersion": 2,
        "scoreRange": [MIN_SCORE, MAX_SCORE],
        "standardGroupSizeRange": [1, 4],
        "status": "ELIGIBLE" if eligible else "NOT_ELIGIBLE",
        "version": version,
    }
    _write_json(root / "metadata.json", metadata)

    manifest_files = {
        MODEL_FILENAME: model_hash,
        DATASET_FILENAME: dataset_hash,
        "metadata.json": _sha256(root / "metadata.json"),
        "metrics.json": _sha256(root / "metrics.json"),
    }
    _write_json(root / "sha256.json", {"algorithm": "sha256", "files": manifest_files})

    return {
        "rows": len(frame),
        "modelSha256": model_hash,
        "version": version,
        "metrics": measured,
        "eligible": eligible,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--artifacts", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args()
    result = build(args.artifacts)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if not result["eligible"]:
        print(
            "WARNING: model did not meet eligibility thresholds. "
            "The runtime will serve deterministic rule scores only."
        )


if __name__ == "__main__":
    main()
